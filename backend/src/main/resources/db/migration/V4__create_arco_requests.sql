CREATE TABLE solicitudes_arco (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo VARCHAR(20) NOT NULL CHECK (tipo IN ('ACCESO', 'RECTIFICACION', 'CANCELACION', 'OPOSICION')),
    descripcion VARCHAR(2000) NOT NULL CHECK (CHAR_LENGTH(TRIM(descripcion)) > 0),
    estado VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE'
        CHECK (estado IN ('PENDIENTE', 'EN_REVISION', 'RESUELTA', 'RECHAZADA')),
    respuesta VARCHAR(2000)
);
